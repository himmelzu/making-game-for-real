(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.FMFaceRepair = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  const MAX_CONFIGS = 256, MAX_XML_BYTES = 4 * 1024 * 1024, MAX_ROWS = 100000;
  function need(ok, message) { if (!ok) throw new Error(message); }
  function clean(value) { return String(value == null ? '' : value).normalize('NFC').trim(); }
  function path(value) {
    const result = clean(value).replace(/\\/g, '/');
    need(result && result.length <= 1000 && !result.startsWith('/') && !/[\u0000-\u001f:]/.test(result)
      && result.split('/').every(part => part && part !== '.' && part !== '..' && !/[. ]$/.test(part)), '안전한 폴더 내부 상대 경로가 필요합니다: ' + result);
    return result;
  }
  function key(value) { return path(value).toLowerCase(); }
  function unescapeXml(value) {
    need(!/[<]/.test(value), 'XML 속성 안의 잘못된 문자가 있습니다.');
    return value.replace(/&([^;\s]+);|&/g, (whole, entity) => {
      const named = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };
      if (entity && Object.hasOwn(named, entity)) return named[entity];
      let code;
      if (/^#x[0-9a-f]+$/i.test(entity || '')) code = parseInt(entity.slice(2), 16);
      else if (/^#[0-9]+$/.test(entity || '')) code = Number(entity.slice(1));
      need(Number.isInteger(code) && (code === 9 || code === 10 || code === 13 || (code >= 32 && code <= 0xD7FF) || (code >= 0xE000 && code <= 0xFFFD) || (code >= 0x10000 && code <= 0x10FFFF)), '지원하지 않는 XML 엔티티입니다.');
      return String.fromCodePoint(code);
    });
  }
  function escapeAttribute(value, quote) {
    const escaped = value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    return quote === '"' ? escaped.replace(/"/g, '&quot;') : escaped.replace(/'/g, '&apos;');
  }
  function readTag(text, start) {
    let i = start + 1, quote = '';
    while (i < text.length) {
      const c = text[i];
      if (quote) { if (c === quote) quote = ''; }
      else if (c === '"' || c === "'") quote = c;
      else if (c === '>') return i + 1;
      else if (c === '<') throw new Error('XML 태그가 잘못되었습니다.');
      i++;
    }
    throw new Error('XML 태그가 닫히지 않았습니다.');
  }
  function attributes(text, start, end) {
    const found = Object.create(null);
    let i = start;
    while (i < end) {
      const begin = i;
      while (/\s/.test(text[i] || '') && i < end) i++;
      if (i >= end) break;
      need(i > begin, 'XML 속성 사이에 공백이 필요합니다.');
      const match = /^[A-Za-z_][A-Za-z0-9_.:-]*/.exec(text.slice(i, end));
      need(match, 'XML 속성 이름을 확인하세요.');
      const name = match[0]; i += name.length;
      while (/\s/.test(text[i] || '') && i < end) i++;
      need(text[i++] === '=', 'XML 속성의 = 기호가 없습니다.');
      while (/\s/.test(text[i] || '') && i < end) i++;
      const quote = text[i++]; need(quote === '"' || quote === "'", 'XML 속성의 따옴표가 없습니다.');
      const valueStart = i, valueEnd = text.indexOf(quote, i);
      need(valueEnd >= i && valueEnd < end, 'XML 속성의 따옴표가 닫히지 않았습니다.');
      need(!Object.hasOwn(found, name), 'XML 속성이 중복되었습니다: ' + name);
      found[name] = { value: unescapeXml(text.slice(valueStart, valueEnd)), start: valueStart, end: valueEnd, quote };
      i = valueEnd + 1;
    }
    return found;
  }
  // Locate only direct mapping records. Edits splice their original attribute or
  // record spans; declarations, comments, settings, whitespace and other XML are
  // never regenerated by a serializer. The browser also validates XML first.
  function readConfig(config) {
    const relative = path(config.path), source = String(config.text);
    need(/(^|\/)config\.xml$/i.test(relative), 'config.xml만 수정할 수 있습니다.');
    need(source.length <= MAX_XML_BYTES, 'config.xml 하나는 4MiB 이하로 나누어 주세요.');
    need(!/<!\s*(?:DOCTYPE|ENTITY)\b/i.test(source), '외부 엔티티나 DTD가 있는 XML은 처리하지 않습니다.');
    const stack = [], records = [];
    let i = 0, roots = 0, maps = 0;
    while (i < source.length) {
      const start = source.indexOf('<', i);
      const tail = source.slice(i, start < 0 ? source.length : start);
      if (!stack.length) need(!tail.replace(/^\uFEFF/, '').trim(), 'XML 루트 밖에 잘못된 내용이 있습니다.');
      if (start < 0) { i = source.length; break; }
      if (source.startsWith('<!--', start)) { const close = source.indexOf('-->', start + 4); need(close >= 0, 'XML 주석이 닫히지 않았습니다.'); i = close + 3; continue; }
      if (source.startsWith('<![CDATA[', start)) { need(stack.length, 'XML 루트 밖의 CDATA입니다.'); const close = source.indexOf(']]>', start + 9); need(close >= 0, 'CDATA가 닫히지 않았습니다.'); i = close + 3; continue; }
      if (source.startsWith('<?', start)) { const close = source.indexOf('?>', start + 2); need(close >= 0, 'XML 선언이 닫히지 않았습니다.'); i = close + 2; continue; }
      const end = readTag(source, start), body = source.slice(start, end);
      const closing = /^<\/([A-Za-z_][A-Za-z0-9_.:-]*)\s*>$/.exec(body);
      if (closing) {
        const node = stack.pop(); need(node && node.name === closing[1], 'XML 닫는 태그가 일치하지 않습니다.');
        if (node.mapping) node.mapping.end = end;
        i = end; continue;
      }
      const opening = /^<([A-Za-z_][A-Za-z0-9_.:-]*)/.exec(body);
      need(opening, '지원하지 않는 XML 태그입니다.');
      const name = opening[1], selfClosing = /\/\s*>$/.test(body);
      const attributeEnd = selfClosing ? start + body.lastIndexOf('/') : end - 1;
      const attrs = attributes(source, start + opening[0].length, attributeEnd);
      if (!stack.length) { roots++; need(roots === 1 && name === 'record', '루트 record가 하나인 FM config.xml을 사용하세요.'); }
      const parent = stack[stack.length - 1], node = { name, attrs, mapping: null, maps: false };
      if (name === 'list' && attrs.id && attrs.id.value === 'maps') { maps++; node.maps = true; }
      if (parent && parent.maps && name === 'record' && attrs.from && attrs.to) {
        const mapping = { index: records.length, from: attrs.from.value, to: attrs.to.value, start, end: selfClosing ? end : null, toSpan: attrs.to };
        records.push(mapping); node.mapping = mapping;
      }
      if (!selfClosing) stack.push(node);
      i = end;
    }
    need(!stack.length && roots === 1 && maps === 1, '닫힌 루트 record와 maps 목록 하나가 필요합니다.');
    need(records.length <= MAX_ROWS && records.every(record => record.end !== null), 'config 매핑 개수나 닫는 태그를 확인하세요.');
    return { path: relative, text: source, records };
  }
  function portrait(value) {
    const match = /^graphics\/pictures\/person\/(r-)?([0-9]{1,18})\/portrait$/i.exec(value);
    if (!match) return null;
    const numeric = match[2].replace(/^0+(?=\d)/, '');
    need(numeric !== '0', 'config에 ID 0이 있습니다.');
    return { prefix: match[1] || '', id: numeric, key: (match[1] ? 'r-' : '') + numeric };
  }
  function photoPath(configPath, from) {
    const relative = path(from), folder = configPath.includes('/') ? configPath.slice(0, configPath.lastIndexOf('/') + 1) : '';
    return path(folder + relative + (/\.png$/i.test(relative) ? '' : '.png'));
  }
  function parseConfigs(input) {
    need(Array.isArray(input) && input.length > 0 && input.length <= MAX_CONFIGS, '얼굴팩의 config.xml을 1~256개 선택하세요.');
    const seen = new Set();
    return input.map(item => {
      const config = readConfig(item), normalized = key(config.path);
      need(!seen.has(normalized), '같은 config 경로가 중복되었습니다: ' + config.path); seen.add(normalized);
      config.records.forEach(row => {
        row.target = portrait(row.to);
        if (row.target) row.photo = photoPath(config.path, row.from);
      });
      return config;
    });
  }
  function catalog(input) {
    need(Array.isArray(input) && input.length > 0 && input.length <= 10000, '검수한 이름·사진 목록이 필요합니다.');
    const seen = new Set();
    function identityName(value) {
      const name = clean(value);
      need(name && name.length <= 200 && !/[\u0000-\u001f]/.test(name), '검수 사진 이름 형식을 확인하세요.');
      return name;
    }
    return input.map(identity => {
      const name = identityName(identity.name), relative = path(identity.path), hash = clean(identity.sha256).toLowerCase();
      need(/\.png$/i.test(relative) && /^[a-f0-9]{64}$/.test(hash), 'PNG 경로와 검수 원본 SHA-256이 있는 사진 목록만 사용합니다.');
      need(!seen.has(key(relative)), '검수 사진 경로가 중복되었습니다.'); seen.add(key(relative));
      const aliases = identity.aliases == null ? [] : identity.aliases;
      need(Array.isArray(aliases) && aliases.length <= 32, '검수한 이름 별칭은 배열로 지정하세요.');
      const caption = identity.caption == null ? name : identityName(identity.caption);
      need(identity.requiresReview == null || typeof identity.requiresReview === 'boolean', '이름 검토 표시는 참 또는 거짓으로 지정하세요.');
      return { name, path: relative, sha256: hash, aliases: [...new Set(aliases.map(identityName))].filter(alias => alias !== name),
        caption, requiresReview: identity.requiresReview === true };
    });
  }
  function nameIndex(identities) {
    const primary = new Map(), aliases = new Map();
    identities.forEach(identity => {
      if (!primary.has(identity.name)) primary.set(identity.name, []);
      primary.get(identity.name).push(identity);
      identity.aliases.forEach(name => {
        if (!aliases.has(name)) aliases.set(name, []);
        aliases.get(name).push(identity);
      });
    });
    // A corrected primary name takes precedence over another photo's original
    // caption alias. Multiple primary matches remain ambiguous.
    return new Map([...aliases, ...primary]);
  }
  function plan(input) {
    const configs = parseConfigs(input.configs), roster = input.roster, identities = catalog(input.catalog), photos = input.photos;
    need(Array.isArray(roster) && roster.length > 0 && roster.length <= MAX_ROWS, '실제 선수 ID·이름 목록이 필요합니다.');
    need(Array.isArray(photos), '검수한 이름·사진 목록이 필요합니다.');
    const ids = new Set(), playersByName = new Map(), identitiesByName = nameIndex(identities), photosByPath = new Map(), sources = new Map();
    roster.forEach(person => {
      const id = clean(person.id).replace(/^r-/i, ''), name = clean(person.name);
      need(/^[1-9][0-9]{0,17}$/.test(id) && name, '실제 선수 ID·이름 형식을 확인하세요.');
      need(!ids.has(id), '실제 선수 ID가 중복되었습니다: ' + id); ids.add(id);
      if (!playersByName.has(name)) playersByName.set(name, []);
      playersByName.get(name).push({ ...person, id, name });
    });
    photos.forEach(photo => {
      const relative = path(photo.path), normalized = key(relative);
      need(/\.png$/i.test(relative) && !photosByPath.has(normalized), '사진 경로가 중복되었거나 PNG가 아닙니다: ' + relative);
      photosByPath.set(normalized, photo);
    });
    const rows = [];
    configs.forEach(config => config.records.forEach(row => {
      row.config = config; row.uid = config.path + ':' + row.index; rows.push(row);
      if (!row.target) return;
      const normalized = key(row.photo);
      if (!sources.has(normalized)) sources.set(normalized, []);
      sources.get(normalized).push(row);
    }));
    const assignments = [], ambiguous = [], unmatched = [];
    playersByName.forEach((people, name) => {
      const identities = identitiesByName.get(name);
      if (!identities) { unmatched.push(...people); return; }
      if (people.length !== 1 || identities.length !== 1) { ambiguous.push(...people.map(person => ({ ...person, reason: '이름이 명단 또는 사진 목록에서 둘 이상입니다.' }))); return; }
      const person = people[0], identity = identities[0], photo = photosByPath.get(key(identity.path));
      need(photo, name + ': 검수한 사진을 찾지 못했습니다. celeb 폴더 전체를 선택하세요.');
      need(clean(photo.sha256).toLowerCase() === identity.sha256, name + ': 검수한 원본 사진과 SHA-256이 다릅니다.');
      const mappings = sources.get(key(identity.path)) || [];
      need(mappings.length === 1, name + ': 해당 사진의 기존 portrait 연결이 없거나 여러 개여서 자동으로 정할 수 없습니다.');
      const row = mappings[0], target = 'graphics/pictures/person/' + row.target.prefix + person.id + '/portrait';
      assignments.push({ id: person.id, name, catalogName: identity.name, captionName: identity.caption,
        captionDiffers: name !== identity.caption, requiresReview: identity.requiresReview,
        club: clean(person.club), photo: identity.path, sha256: identity.sha256,
        config: row.config.path, oldTarget: row.to, newTarget: target, targetKey: portrait(target).key, rowUid: row.uid, changed: row.to !== target });
    });
    const assignedRows = new Map(), desired = new Map();
    assignments.forEach(assignment => {
      need(!assignedRows.has(assignment.rowUid) && !desired.has(assignment.targetKey), '여러 사진이 같은 실제 선수 ID에 연결됩니다.');
      assignedRows.set(assignment.rowUid, assignment); desired.set(assignment.targetKey, assignment);
    });
    const removed = [];
    rows.forEach(row => {
      if (row.target && desired.has(row.target.key) && !assignedRows.has(row.uid)) {
        const correct = desired.get(row.target.key);
        removed.push({ rowUid: row.uid, config: row.config.path, photo: row.photo, oldTarget: row.to, correctedName: correct.name,
          reason: '확인한 실제 선수 ID에 다른 사진이 연결되어 있어 중복 연결을 제외합니다.' });
      }
    });
    const removedIds = new Set(removed.map(row => row.rowUid)), retainedPhotos = new Set(), resultingTargets = new Map();
    rows.forEach(row => {
      if (!row.target || removedIds.has(row.uid)) return;
      retainedPhotos.add(key(row.photo));
      const assignment = assignedRows.get(row.uid), targetKey = assignment ? assignment.targetKey : row.target.key;
      if (!resultingTargets.has(targetKey)) resultingTargets.set(targetKey, []);
      resultingTargets.get(targetKey).push(row.uid);
    });
    desired.forEach((assignment, targetKey) => need(resultingTargets.get(targetKey).length === 1, '수정 대상 ID의 사진 충돌을 해소하지 못했습니다.'));
    const unmapped = [...new Map(removed.filter(row => !retainedPhotos.has(key(row.photo))).map(row => [key(row.photo), row])).values()];
    const remainingDuplicateTargets = [...resultingTargets].filter(([, same]) => same.length > 1).map(([targetKey, same]) => ({ targetKey, count: same.length }));
    const changedConfigs = [];
    configs.forEach(config => {
      const edits = [];
      config.records.forEach(row => {
        if (removedIds.has(row.uid)) edits.push({ start: row.start, end: row.end, replacement: '' });
        else {
          const assignment = assignedRows.get(row.uid);
          if (assignment && assignment.changed) edits.push({ start: row.toSpan.start, end: row.toSpan.end, replacement: escapeAttribute(assignment.newTarget, row.toSpan.quote) });
        }
      });
      if (!edits.length) return;
      edits.sort((a, b) => b.start - a.start);
      let text = config.text, previous = config.text.length;
      edits.forEach(edit => { need(edit.end <= previous, '겹치는 XML 수정 요청입니다.'); text = text.slice(0, edit.start) + edit.replacement + text.slice(edit.end); previous = edit.start; });
      readConfig({ path: config.path, text });
      changedConfigs.push({ path: config.path, text, updates: assignments.filter(a => a.config === config.path && a.changed).length,
        removed: removed.filter(a => a.config === config.path).length });
    });
    return { format: 'fm26-face-config-repair-v1', assignments, ambiguous, unmatched, removed, unmapped, remainingDuplicateTargets,
      changedConfigs, configCount: configs.length, portraitMappings: rows.filter(row => row.target).length,
      photoCount: photos.length, verifiedCatalogCount: identities.length, changedAssignments: assignments.filter(row => row.changed).length };
  }
  return { path, key, readConfig, parseConfigs, catalog, nameIndex, plan };
});
